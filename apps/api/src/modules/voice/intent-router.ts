/**
 * ISO instant → spoken date, e.g. '2026-10-05T…' en → '5 October 2026'.
 * Deterministic (UTC calendar fields); invalid input throws so a malformed
 * due date can never be smuggled into a spoken answer.
 */
export function speakDate(iso: string, locale?: string): string {
  const date = new Date(iso);
  if (Number.isNaN(date.getTime())) {
    throw new RangeError(`speakDate expects an ISO date, got '${iso}'`);
  }
  const names = MONTH_NAMES[normalizeVoiceIntentLocale(locale)];
  return `${date.getUTCDate()} ${names[date.getUTCMonth()]} ${date.getUTCFullYear()}`;
}
