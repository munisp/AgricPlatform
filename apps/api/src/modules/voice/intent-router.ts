/**
 * Voice Teller intent router (Stage 27, Innovation 6) — a pure,
 * deterministic grammar-slot router for transactional voice intents. Two
 * input modalities resolve to the same four read-only account intents:
 *
 *   DTMF    — the IVR account-menu digit (1..5), see ACCOUNT_MENU_DTMF.
 *   ASR slots — keyword-phrase matching over the (already transcribed)
 *             utterance, per locale with English fallback.
 *
 * There is NO free-form generation for account data: anything that does
 * not resolve to exactly one intent returns `undefined`, and the caller
 * routes the turn to the existing agronomy RAG flow or human escalation,
 * unchanged. Account values are read from the ledger/credit/vsla/voucher
 * read models by the service layer and rendered through the fixed speech
 * templates in intent-templates.ts — never generated by a model.
 *
 * Locale keyword content for ha/yo/ig is a first-pass deterministic
 * grammar; native-speaker review is a content dependency (HANDOFF.md).
 * The matching PRECEDENCE rule is what keeps the router deterministic:
 * the intent with the longest matched phrase wins; ties break in catalog
 * (VOICE_INTENT_IDS) order.
 */

export const VOICE_TELLER_FLAG = 'voice-teller';

/** The complete transactional-intent catalog (read-only account facts). */
export const VOICE_INTENT_IDS = [
  'balance.savings',
  'balance.float',
  'loan.next_installment',
  'vsla.position',
  'voucher.status'
] as const;
export type VoiceIntentId = (typeof VOICE_INTENT_IDS)[number];

/** Locales with speech templates + ASR grammars this wave. */
export const VOICE_INTENT_LOCALES = ['en', 'ha', 'yo', 'ig'] as const;
export type VoiceIntentLocale = (typeof VOICE_INTENT_LOCALES)[number];

/** Unknown/unsupported locales fall back to English templates + grammar. */
export function normalizeVoiceIntentLocale(locale?: string): VoiceIntentLocale {
  const lowered = (locale ?? 'en').trim().toLowerCase();
  return (VOICE_INTENT_LOCALES as readonly string[]).includes(lowered)
    ? (lowered as VoiceIntentLocale)
    : 'en';
}

