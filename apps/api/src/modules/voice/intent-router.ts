/** Lowercases, strips punctuation (keeps letters/digits/spaces), collapses whitespace. */
export function normalizeTranscript(transcript: string): string {
  return transcript
    .toLowerCase()
    .replace(/[^a-z0-9 ]/g, ' ')
    .split(' ')
    .filter((word) => word.length > 0)
    .join(' ');
}

interface GrammarMatch {
  intent: VoiceIntentId;
  /** Length of the longest matched phrase (precedence rule). */
  matchedLength: number;
}

/**
 * Resolves an ASR transcript to exactly one intent, or undefined when the
 * utterance matches nothing (route to agronomy RAG / escalation). The
 * longest matched phrase wins; ties break in catalog order. A transcript
 * mentioning two intents with different phrase lengths resolves to the
 * more specific (longer) phrase — e.g. 'float balance' beats 'balance'.
 */
export function intentForTranscript(transcript: string, locale?: string): VoiceIntentId | undefined {
  const normalized = normalizeTranscript(transcript);
  if (normalized.length === 0) {
    return undefined;
  }
  const resolvedLocale = normalizeVoiceIntentLocale(locale);
  let best: GrammarMatch | undefined;
  for (const intent of VOICE_INTENT_IDS) {
    const grammar = ASR_GRAMMAR[intent];
    const phrases = resolvedLocale === 'en' ? grammar.en : [...grammar.en, ...grammar[resolvedLocale]];
    for (const phrase of phrases) {
      if (normalized.includes(phrase) && (!best || phrase.length > best.matchedLength)) {
        best = { intent, matchedLength: phrase.length };
      }
    }
  }
  return best?.intent;
}

/* ------------------------------------------------------ number speech --- */

/**
 * Deterministic thousands grouping (comma-separated), implemented in-repo
 * so known-answer tests never depend on the host ICU build.
 */
export function formatIntegerSpeech(value: number): string {
  if (!Number.isSafeInteger(value) || value < 0) {
    throw new RangeError(`formatIntegerSpeech expects a non-negative safe integer, got ${value}`);
  }
  const digits = String(value);
  const groups: string[] = [];
  for (let end = digits.length; end > 0; end -= 3) {
    groups.unshift(digits.slice(Math.max(0, end - 3), end));
  }
  return groups.join(',');
}

/** Locale glue words for money speech (naira/kobo are loanwords everywhere). */
const MONEY_WORDS: Readonly<Record<VoiceIntentLocale, { and: string }>> = {
  en: { and: 'and' },
  ha: { and: 'da' },
  yo: { and: 'ati' },
  ig: { and: 'na' }
};

/**
 * kobo → spoken naira. 123456 kobo, en → '1,234 naira and 56 kobo'.
 * Zero-kobo amounts omit the kobo clause: 100000 → '1,000 naira'.
 * Sub-naira amounts speak kobo only: 75 → '75 kobo'.
 */
export function speakMoneyKobo(amountKobo: number, locale?: string): string {
  if (!Number.isSafeInteger(amountKobo) || amountKobo < 0) {
    throw new RangeError(`speakMoneyKobo expects a non-negative safe integer, got ${amountKobo}`);
  }
  const words = MONEY_WORDS[normalizeVoiceIntentLocale(locale)];
  const naira = Math.floor(amountKobo / 100);
  const kobo = amountKobo % 100;
  if (naira === 0) {
    return `${formatIntegerSpeech(kobo)} kobo`;
  }
  const nairaPart = `${formatIntegerSpeech(naira)} naira`;
  return kobo === 0 ? nairaPart : `${nairaPart} ${words.and} ${formatIntegerSpeech(kobo)} kobo`;
}

