/**
 * IVR account-menu digit → intent. The menu prompt in ivr/call-flow.ts
 * reads these in key order, so the mapping and the spoken menu can never
 * drift apart.
 */
export const ACCOUNT_MENU_DTMF: Readonly<Record<string, VoiceIntentId>> = {
  '1': 'balance.savings',
  '2': 'balance.float',
  '3': 'loan.next_installment',
  '4': 'vsla.position',
  '5': 'voucher.status'
};

export function intentForDtmf(digit: string): VoiceIntentId | undefined {
  return ACCOUNT_MENU_DTMF[digit.trim()];
}

